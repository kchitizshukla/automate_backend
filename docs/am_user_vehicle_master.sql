-- ---------------------------------------------------------------------
-- 4. MIGRATE EXISTING VEHICLE ROWS
--    Every pre-existing row is a car, so:
--      make  -> vehicle_manufacturers.name  (with the two legacy aliases)
--      model -> vehicle_models.name         (category taken from the model)
--    Rows that cannot be matched still get Four Wheeler / Car plus their
--    original text preserved in custom_manufacturer / custom_model, so the
--    user's garage never loses a vehicle and nothing 404s.
-- ---------------------------------------------------------------------

-- 4.1 Manufacturer, by exact name or a known legacy alias.
WITH alias(legacy, canonical) AS (
  VALUES ('Tata', 'Tata Motors'), ('MG', 'MG Motor'), ('VW', 'Volkswagen')
)
UPDATE vehicles v
SET vehicle_manufacturer_id = mf.id, updated_at = now()
FROM vehicle_manufacturers mf
LEFT JOIN alias a ON lower(a.canonical) = lower(mf.name)
WHERE v.vehicle_manufacturer_id IS NULL
  AND (lower(mf.name) = lower(v.make) OR lower(a.legacy) = lower(v.make));

-- 4.2 Model within that manufacturer, which also settles the category.
UPDATE vehicles v
SET vehicle_model_id = vm.id,
    vehicle_category_id = vm.vehicle_category_id,
    updated_at = now()
FROM vehicle_models vm
WHERE v.vehicle_model_id IS NULL
  AND v.vehicle_manufacturer_id = vm.vehicle_manufacturer_id
  AND lower(vm.name) = lower(v.model);

-- 4.3 Anything still unmatched: keep the original text and land it on Car.
UPDATE vehicles v
SET vehicle_category_id = COALESCE(v.vehicle_category_id, (SELECT id FROM vehicle_categories WHERE code = 'car')),
    custom_manufacturer = CASE WHEN v.vehicle_manufacturer_id IS NULL THEN v.make ELSE v.custom_manufacturer END,
    custom_model        = CASE WHEN v.vehicle_model_id IS NULL THEN v.model ELSE v.custom_model END,
    updated_at = now()
WHERE v.vehicle_category_id IS NULL
   OR v.vehicle_manufacturer_id IS NULL
   OR v.vehicle_model_id IS NULL;

-- 4.4 Type always follows from the category.
UPDATE vehicles v
SET vehicle_type_id = c.vehicle_type_id, updated_at = now()
FROM vehicle_categories c
WHERE v.vehicle_type_id IS NULL AND v.vehicle_category_id = c.id;

-- 4.5 Normalize registration numbers to the stored form (uppercase, no spaces).
UPDATE vehicles
SET registration_no = upper(replace(replace(registration_no, ' ', ''), '.', '')),
    updated_at = now()
WHERE registration_no <> upper(replace(replace(registration_no, ' ', ''), '.', ''));

