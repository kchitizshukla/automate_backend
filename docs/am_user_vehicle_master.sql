-- =====================================================================
-- FixMyRide - am_user : dynamic multi-vehicle master data
-- Target database : am_user   (PostgreSQL 18, server "automate")
--
-- Purpose
--   Replace the car-only assumption in `vehicles` with a normalized,
--   database-driven taxonomy:
--
--     VEHICLE_TYPE -> VEHICLE_CATEGORY -> VEHICLE_MANUFACTURER
--                  -> VEHICLE_MODEL -> VEHICLE_VARIANT -> VEHICLE_FUEL_TYPE
--
--   Adding a vehicle type, manufacturer, model or variant after this runs is a
--   pure INSERT: both the user web app and the user mobile app pick it up on
--   the next request, with no frontend deployment.
--
-- Safety
--   * ADDITIVE ONLY. Nothing is dropped, nothing existing is renamed.
--   * `vehicles.make` / `.model` are KEPT and stay populated, so the roadside
--     snapshot, service requests, and the mechanic + admin modules are
--     untouched by this change.
--   * Idempotent: safe to run repeatedly (IF NOT EXISTS + ON CONFLICT).
--   * Section 4 back-fills every pre-existing vehicle row onto master records.
--
-- Run with:
--   psql -U postgres -h localhost -d am_user -f docs/am_user_vehicle_master.sql
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. MASTER TABLES
-- ---------------------------------------------------------------------

-- Top of the hierarchy: Two Wheeler, Four Wheeler, Heavy Vehicle, ...
CREATE TABLE IF NOT EXISTS vehicle_types (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL,
    code          TEXT        NOT NULL UNIQUE,
    description   TEXT,
    icon          TEXT,
    display_order INTEGER     NOT NULL DEFAULT 0,
    is_active     INTEGER     NOT NULL DEFAULT 1,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Motorcycle, Scooter, Car, Truck, Tractor, Ambulance, ...
CREATE TABLE IF NOT EXISTS vehicle_categories (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type_id INTEGER     NOT NULL REFERENCES vehicle_types(id) ON DELETE CASCADE,
    name            TEXT        NOT NULL,
    code            TEXT        NOT NULL UNIQUE,
    description     TEXT,
    icon            TEXT,
    -- True for categories that are electric by definition (E-Rickshaw, E-Bus).
    is_electric     INTEGER     NOT NULL DEFAULT 0,
    display_order   INTEGER     NOT NULL DEFAULT 0,
    is_active       INTEGER     NOT NULL DEFAULT 1,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Honda, Tata Motors, Royal Enfield, JCB, ... One brand serves many
-- categories, so the category link lives in a join table rather than a column.
CREATE TABLE IF NOT EXISTS vehicle_manufacturers (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL,
    code          TEXT        NOT NULL UNIQUE,
    description   TEXT,
    logo_url      TEXT,
    display_order INTEGER     NOT NULL DEFAULT 0,
    is_active     INTEGER     NOT NULL DEFAULT 1,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS vehicle_category_manufacturers (
    vehicle_category_id     INTEGER NOT NULL REFERENCES vehicle_categories(id)    ON DELETE CASCADE,
    vehicle_manufacturer_id INTEGER NOT NULL REFERENCES vehicle_manufacturers(id) ON DELETE CASCADE,
    display_order           INTEGER NOT NULL DEFAULT 0,
    is_active               INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (vehicle_category_id, vehicle_manufacturer_id)
);

-- A model belongs to exactly one brand within one category: "Honda Activa"
-- is a Scooter, "Honda City" is a Car.
CREATE TABLE IF NOT EXISTS vehicle_models (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_manufacturer_id INTEGER     NOT NULL REFERENCES vehicle_manufacturers(id) ON DELETE CASCADE,
    vehicle_category_id     INTEGER     NOT NULL REFERENCES vehicle_categories(id)    ON DELETE CASCADE,
    name                    TEXT        NOT NULL,
    code                    TEXT        NOT NULL,
    description             TEXT,
    icon                    TEXT,
    display_order           INTEGER     NOT NULL DEFAULT 0,
    is_active               INTEGER     NOT NULL DEFAULT 1,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (vehicle_manufacturer_id, vehicle_category_id, code)
);

CREATE TABLE IF NOT EXISTS vehicle_variants (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_model_id INTEGER     NOT NULL REFERENCES vehicle_models(id) ON DELETE CASCADE,
    name             TEXT        NOT NULL,
    code             TEXT        NOT NULL,
    description      TEXT,
    display_order    INTEGER     NOT NULL DEFAULT 0,
    is_active        INTEGER     NOT NULL DEFAULT 1,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (vehicle_model_id, code)
);

-- Fuel / power type. Electric is a first-class row here, not a car flavour.
CREATE TABLE IF NOT EXISTS vehicle_fuel_types (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL,
    code          TEXT        NOT NULL UNIQUE,
    description   TEXT,
    icon          TEXT,
    is_electric   INTEGER     NOT NULL DEFAULT 0,
    display_order INTEGER     NOT NULL DEFAULT 0,
    is_active     INTEGER     NOT NULL DEFAULT 1,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Optional narrowing: which power types a given model is actually sold with.
-- When a model has no rows here the API falls back to every active fuel type,
-- so seeding this table is never a prerequisite for adding a model.
CREATE TABLE IF NOT EXISTS vehicle_model_fuel_types (
    vehicle_model_id     INTEGER NOT NULL REFERENCES vehicle_models(id)     ON DELETE CASCADE,
    vehicle_fuel_type_id INTEGER NOT NULL REFERENCES vehicle_fuel_types(id) ON DELETE CASCADE,
    display_order        INTEGER NOT NULL DEFAULT 0,
    is_active            INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (vehicle_model_id, vehicle_fuel_type_id)
);

-- Registration-number format, configurable per type or per category, so a
-- tractor or an earthmover is never forced through a car-shaped validator.
-- Most specific wins: category rule > type rule > global rule.
CREATE TABLE IF NOT EXISTS vehicle_registration_rules (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type_id     INTEGER     REFERENCES vehicle_types(id)      ON DELETE CASCADE,
    vehicle_category_id INTEGER     REFERENCES vehicle_categories(id) ON DELETE CASCADE,
    code                TEXT        NOT NULL UNIQUE,
    -- JavaScript/POSIX-compatible regex source, matched case-insensitively.
    pattern             TEXT,
    placeholder         TEXT,
    help_text           TEXT,
    min_length          INTEGER     NOT NULL DEFAULT 4,
    max_length          INTEGER     NOT NULL DEFAULT 20,
    is_required         INTEGER     NOT NULL DEFAULT 1,
    display_order       INTEGER     NOT NULL DEFAULT 0,
    is_active           INTEGER     NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Indexes for the dependent-dropdown queries.
CREATE INDEX IF NOT EXISTS idx_vehicle_categories_type   ON vehicle_categories(vehicle_type_id) WHERE is_active = 1;
CREATE INDEX IF NOT EXISTS idx_vehicle_models_mfr        ON vehicle_models(vehicle_manufacturer_id) WHERE is_active = 1;
CREATE INDEX IF NOT EXISTS idx_vehicle_models_category   ON vehicle_models(vehicle_category_id) WHERE is_active = 1;
CREATE INDEX IF NOT EXISTS idx_vehicle_variants_model    ON vehicle_variants(vehicle_model_id) WHERE is_active = 1;
CREATE INDEX IF NOT EXISTS idx_vehicle_cat_mfr_category  ON vehicle_category_manufacturers(vehicle_category_id);
-- Case-insensitive prefix/substring search over the two large tables.
CREATE INDEX IF NOT EXISTS idx_vehicle_models_name_lower ON vehicle_models(lower(name));
CREATE INDEX IF NOT EXISTS idx_vehicle_mfr_name_lower    ON vehicle_manufacturers(lower(name));


-- ---------------------------------------------------------------------
-- 2. EXTEND `vehicles` (additive — existing columns untouched)
-- ---------------------------------------------------------------------
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vehicle_type_id         INTEGER REFERENCES vehicle_types(id)         ON DELETE SET NULL;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vehicle_category_id     INTEGER REFERENCES vehicle_categories(id)    ON DELETE SET NULL;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vehicle_manufacturer_id INTEGER REFERENCES vehicle_manufacturers(id) ON DELETE SET NULL;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vehicle_model_id        INTEGER REFERENCES vehicle_models(id)        ON DELETE SET NULL;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vehicle_variant_id      INTEGER REFERENCES vehicle_variants(id)      ON DELETE SET NULL;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS vehicle_fuel_type_id    INTEGER REFERENCES vehicle_fuel_types(id)    ON DELETE SET NULL;
-- Free text captured only when the user picks the "Other / Not listed" option.
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS custom_manufacturer TEXT;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS custom_model        TEXT;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS custom_variant      TEXT;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS nickname            TEXT;
-- Soft delete. service_requests.vehicle_id cascades, so a vehicle with history
-- is archived rather than removed; the user's bookings survive either way.
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS is_active  INTEGER     NOT NULL DEFAULT 1;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

CREATE INDEX IF NOT EXISTS idx_vehicles_user_active ON vehicles(user_id) WHERE is_active = 1;


